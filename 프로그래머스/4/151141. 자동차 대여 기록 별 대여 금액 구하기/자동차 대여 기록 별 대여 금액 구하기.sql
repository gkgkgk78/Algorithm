SELECT CH.HISTORY_ID ,
(
    CASE
        WHEN DATEDIFF(CH.END_DATE,START_DATE)+1<7 
            THEN CR.DAILY_FEE *(DATEDIFF(CH.END_DATE,START_DATE)+1)
        WHEN DATEDIFF(CH.END_DATE,START_DATE)+1>=7  
            AND DATEDIFF(CH.END_DATE,START_DATE)+1<30
            THEN CR.DAILY_FEE *(1-0.01*
        (   SELECT DISCOUNT_RATE
            FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
            WHERE CAR_TYPE='트럭' AND DURATION_TYPE LIKE '%7%'
        )) * (DATEDIFF(CH.END_DATE,START_DATE)+1)
        WHEN DATEDIFF(CH.END_DATE,START_DATE)+1>=30  
            AND DATEDIFF(CH.END_DATE,START_DATE)+1<90
            THEN CR.DAILY_FEE *(1-0.01*
        (   SELECT DISCOUNT_RATE
            FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
            WHERE CAR_TYPE='트럭' AND DURATION_TYPE LIKE '%30%'
        )) * (DATEDIFF(CH.END_DATE,START_DATE)+1)
        WHEN DATEDIFF(CH.END_DATE,START_DATE)+1>=90
            THEN CR.DAILY_FEE *(1-0.01*
        (   SELECT DISCOUNT_RATE
            FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
            WHERE CAR_TYPE='트럭' AND DURATION_TYPE LIKE '%90%'
        )) * (DATEDIFF(CH.END_DATE,START_DATE)+1)
       
    END
) FEE
FROM CAR_RENTAL_COMPANY_CAR  CR
JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY  CH ON CR.CAR_ID=CH.CAR_ID
WHERE CAR_TYPE='트럭'
ORDER BY FEE DESC , CH.HISTORY_ID DESC


